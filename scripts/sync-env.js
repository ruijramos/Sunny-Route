const fs = require('fs');
const path = require('path');

function getEnvValue(key) {
  // First priority: process.env (e.g. system env or CI/CD)
  if (process.env[key]) {
    return process.env[key].trim().replace(/^['"]|['"]$/g, '');
  }

  // Second priority: .env file
  const envPath = path.resolve(__dirname, '../.env');
  if (fs.existsSync(envPath)) {
    const lines = fs.readFileSync(envPath, 'utf8').split('\n');
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const match = trimmed.match(new RegExp(`^${key}\\s*=\\s*(.*)$`));
      if (match) {
        return match[1].trim().replace(/^['"]|['"]$/g, '');
      }
    }
  }

  return '';
}

const groqApiKey = getEnvValue('GROQ_API_KEY');

const envDir = path.resolve(__dirname, '../src/app/environments');
if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}

function maskKey(key) {
  if (!key) return '(not configured - running in zero-key local mode)';
  if (key.length <= 10) return '***';
  return key.slice(0, 7) + '...' + key.slice(-4);
}

const devEnvContent = `// Automatically generated by scripts/sync-env.js
export const environment = {
  production: false,
  groq_api_key: '${groqApiKey}',
  groq_api_url: 'https://api.groq.com/openai/v1/chat/completions'
};
`;

const prodEnvContent = `// Automatically generated by scripts/sync-env.js
export const environment = {
  production: true,
  groq_api_key: '${groqApiKey}',
  groq_api_url: 'https://api.groq.com/openai/v1/chat/completions'
};
`;

fs.writeFileSync(path.join(envDir, 'environment.ts'), devEnvContent, 'utf8');
fs.writeFileSync(path.join(envDir, 'environment.prod.ts'), prodEnvContent, 'utf8');

console.log('----------------------------------------------------');
